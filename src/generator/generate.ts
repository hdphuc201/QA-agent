// `generate` stage: READY cases of the plan → `<testOutputRoot>/` (specs, runtime fixtures,
// Playwright config, case map). Idempotent: a manifest of content hashes protects files the user
// edited; files without the generated header are never touched.

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import type { ProjectConfig } from '../config/project-config.schema.ts';
import { assertWritable, writeProjectFile } from '../config/write-guard.ts';
import { runnableCases } from '../planning/planner.ts';
import type { TestCase, TestPlan } from '../planning/schema.ts';
import { specFileName, specSource } from './codegen.ts';

export const GENERATED_MARK = 'GENERATED by QA Agent';
export const MANIFEST = '.qa-agent-manifest.json';
export const FIXTURES = 'qa-agent.fixtures.ts';
export const PW_CONFIG = 'playwright.qa-agent.config.ts';
export const GLOBAL_SETUP = 'qa-agent.global-setup.ts';
export const GLOBAL_TEARDOWN = 'qa-agent.global-teardown.ts';

/** `e2e/generated` → `../..` (from the output root back to the project root). */
export function upTo(outputRoot: string): string {
  return path.posix.relative(path.posix.join('/x', outputRoot.replace(/\\/g, '/')), '/x') || '.';
}

/** What the generated global hooks do for this config. */
export function lifecycle(config: ProjectConfig): {
  resetBefore: boolean;
  resetAfter: boolean;
  purge: boolean;
} {
  const on = config.testData?.resetPath ? config.testData.resetOn : null;
  return {
    resetBefore: on === 'before' || on === 'both',
    resetAfter: on === 'after' || on === 'both',
    purge: config.session.cache && config.session.purgeAfterRun,
  };
}

export function globalSetupSource(opts: { reset: boolean; purge: boolean }): string {
  return [
    `// ${GENERATED_MARK} — do not edit. Before the run: ${[opts.purge ? 'delete leftover cached sessions (e.g. from a cancelled run)' : '', opts.reset ? 'reset test data' : ''].filter(Boolean).join(', ')}.`,
    `import type { FullConfig } from '@playwright/test';`,
    `import { purgeSessions, resetTestData } from './qa-agent.fixtures';`,
    ``,
    `export default async function globalSetup(config: FullConfig): Promise<void> {`,
    ...(opts.purge ? [`  purgeSessions(config);`] : [`  void config;`, `  void purgeSessions;`]),
    ...(opts.reset ? [`  await resetTestData();`] : [`  void resetTestData;`]),
    `}`,
    ``,
  ].join('\n');
}

export function globalTeardownSource(opts: { reset: boolean; purge: boolean }): string {
  return [
    `// ${GENERATED_MARK} — do not edit. After the run: ${[opts.reset ? 'reset test data' : '', opts.purge ? 'delete cached sessions' : ''].filter(Boolean).join(', ')}.`,
    `import type { FullConfig } from '@playwright/test';`,
    `import { purgeSessions, resetTestData } from './qa-agent.fixtures';`,
    ``,
    `export default async function globalTeardown(config: FullConfig): Promise<void> {`,
    ...(opts.purge ? [`  purgeSessions(config);`] : [`  void config;`, `  void purgeSessions;`]),
    ...(opts.reset ? [`  await resetTestData();`] : [`  void resetTestData;`]),
    `}`,
    ``,
  ].join('\n');
}

/** Fixed formatting so output never depends on the target project's Prettier config. */
export const FORMAT_OPTIONS = {
  singleQuote: true,
  printWidth: 100,
  trailingComma: 'all',
  endOfLine: 'lf',
  parser: 'typescript',
} as const;

export interface Manifest {
  schemaVersion: 1;
  generator: 'qa-agent';
  planHash: string;
  files: Record<string, string>; // relative path -> sha256 of the content we wrote
}

export interface GenerateResult {
  outputRoot: string;
  written: string[];
  unchanged: string[];
  conflicts: { file: string; reason: string; proposed: string }[];
  removed: string[];
  keptStale: string[];
  cases: { id: string; file: string; title: string }[];
  skipped: { id: string; status: string }[];
  formatted: boolean;
}

const sha = (s: string) => createHash('sha256').update(s).digest('hex');
const toPosix = (p: string) => p.split(path.sep).join('/');

async function format(source: string): Promise<{ text: string; formatted: boolean }> {
  try {
    const prettier = await import('prettier');
    return { text: await prettier.format(source, FORMAT_OPTIONS), formatted: true };
  } catch (err) {
    if (err instanceof Error && /Cannot find (module|package)/.test(err.message))
      return { text: source, formatted: false };
    throw err;
  }
}

/** Stable hash of the READY cases (what the specs depend on). */
export function planHash(cases: TestCase[]): string {
  return sha(JSON.stringify(cases.map((c) => ({ ...c, provenance: undefined })))).slice(0, 12);
}

export function fixturesSource(runtimeFile: string, config: ProjectConfig): string {
  const runtime = fs.readFileSync(runtimeFile, 'utf8');
  const auth = config.exploration.auth;
  const block = [
    '/* QA_AGENT_CONFIG:BEGIN */',
    'export const QA = {',
    `  projectId: ${JSON.stringify(config.projectId)},`,
    `  baseURL: ${JSON.stringify(config.baseURL)},`,
    `  login: ${auth ? JSON.stringify(auth) : 'null'} as { loginPath: string; usernameLabel: string; passwordLabel: string; submitButton: string } | null,`,
    `  accounts: ${JSON.stringify(Object.fromEntries(config.roles.map((r) => [r.name, r.accountKey])))} as Record<string, string>,`,
    `  allowedOrigins: ${JSON.stringify(config.allowedOrigins)} as string[],`,
    `  resetPath: ${config.testData?.resetPath ? JSON.stringify(config.testData.resetPath) : 'null'} as string | null,`,
    `  session: ${JSON.stringify(config.session)},`,
    `  authDir: ${JSON.stringify(`${upTo(config.testOutputRoot)}/qa-artifacts/auth`)},`,
    '};',
    '/* QA_AGENT_CONFIG:END */',
  ].join('\n');
  const out = runtime.replace(
    /\/\* QA_AGENT_CONFIG:BEGIN \*\/[\s\S]*?\/\* QA_AGENT_CONFIG:END \*\//,
    block,
  );
  if (out === runtime && !runtime.includes(block))
    throw new Error('runtime fixtures template has no QA_AGENT_CONFIG block');
  return out;
}

export function playwrightConfigSource(config: ProjectConfig, outputRoot: string): string {
  const { resetBefore, resetAfter, purge } = lifecycle(config);
  // Paths are relative to the config file (which lives in the output root).
  const up = upTo(outputRoot);
  const artifacts = `${up}/qa-artifacts/playwright`;
  return [
    `// ${GENERATED_MARK} — do not edit; regenerate with \`qa-agent generate\`.`,
    `// Run: npx playwright test -c ${toPosix(path.join(outputRoot, PW_CONFIG))}`,
    `import { defineConfig, devices } from '@playwright/test';`,
    ``,
    `const env: Record<string, string | undefined> = (globalThis as unknown as { process?: { env: Record<string, string | undefined> } }).process?.env ?? {};`,
    ``,
    `export default defineConfig({`,
    `  testDir: '.',`,
    `  testMatch: '**/*.spec.ts',`,
    `  fullyParallel: false,`,
    `  // Write-heavy suites default to the configured budget (workers.writeHeavy = ${config.workers.writeHeavy}).`,
    `  workers: Number(env.QA_AGENT_WORKERS ?? ${config.workers.writeHeavy}),`,
    `  retries: Number(env.QA_AGENT_RETRIES ?? 0),`,
    `  timeout: 60_000,`,
    `  forbidOnly: true,`,
    ...(resetBefore || purge ? [`  globalSetup: './${GLOBAL_SETUP}',`] : []),
    ...(resetAfter || purge ? [`  globalTeardown: './${GLOBAL_TEARDOWN}',`] : []),
    `  // Flakes must stay visible: no automatic retries unless QA_AGENT_RETRIES is set.`,
    `  expect: { timeout: 10_000 },`,
    `  outputDir: '${artifacts}/test-results',`,
    `  reporter: [`,
    `    ['list'],`,
    `    ['json', { outputFile: '${artifacts}/results.json' }],`,
    `    ['html', { outputFolder: '${artifacts}/html', open: 'never' }],`,
    `  ],`,
    `  use: {`,
    `    baseURL: env.QA_AGENT_BASE_URL ?? ${JSON.stringify(config.baseURL)},`,
    `    trace: 'retain-on-failure',`,
    `    screenshot: 'only-on-failure',`,
    `    actionTimeout: 10_000,`,
    `    navigationTimeout: 30_000,`,
    `  },`,
    `  projects: [`,
    `    {`,
    `      name: 'chromium',`,
    `      use: { ...devices['Desktop Chrome'], ...(env.QA_AGENT_BROWSER_CHANNEL ? { channel: env.QA_AGENT_BROWSER_CHANNEL } : {}) },`,
    `    },`,
    `  ],`,
    `});`,
    ``,
  ].join('\n');
}

function readManifest(dir: string): Manifest | null {
  const file = path.join(dir, MANIFEST);
  if (!fs.existsSync(file)) return null;
  const m = JSON.parse(fs.readFileSync(file, 'utf8')) as Manifest;
  return m.generator === 'qa-agent' && typeof m.files === 'object' ? m : null;
}

export async function runGenerate(options: {
  projectRoot: string;
  config: ProjectConfig;
  plan: TestPlan;
  runtimeFile: string;
}): Promise<GenerateResult> {
  const { projectRoot, config, plan } = options;
  const outRel = config.testOutputRoot;
  const outDir = path.join(projectRoot, outRel);
  const ready = runnableCases(plan);
  const hash = planHash(ready);

  const byFeature = new Map<string, TestCase[]>();
  for (const c of ready)
    byFeature.set(specFileName(c.feature), [...(byFeature.get(specFileName(c.feature)) ?? []), c]);

  const raw = new Map<string, string>();
  for (const [file, cases] of [...byFeature].sort(([a], [b]) => a.localeCompare(b))) {
    raw.set(file, specSource(cases[0]?.feature ?? null, cases, hash));
  }
  raw.set(FIXTURES, fixturesSource(options.runtimeFile, config));
  raw.set(PW_CONFIG, playwrightConfigSource(config, outRel));
  const life = lifecycle(config);
  if (life.resetBefore || life.purge)
    raw.set(GLOBAL_SETUP, globalSetupSource({ reset: life.resetBefore, purge: life.purge }));
  if (life.resetAfter || life.purge)
    raw.set(GLOBAL_TEARDOWN, globalTeardownSource({ reset: life.resetAfter, purge: life.purge }));

  const files = new Map<string, string>();
  let formatted = true;
  for (const [file, src] of raw) {
    const f = await format(src);
    formatted &&= f.formatted;
    files.set(file, f.text);
  }
  const caseMap = [...byFeature].flatMap(([file, cases]) =>
    [...cases]
      .sort((a, b) => a.id.localeCompare(b.id))
      .map((c) => ({
        id: c.id,
        file: toPosix(path.join(outRel, file)),
        title: `${c.id} ${c.title}`,
      })),
  );
  files.set(
    'case-map.json',
    `${JSON.stringify({ schemaVersion: 1, planHash: hash, cases: caseMap }, null, 2)}\n`,
  );

  const previous = readManifest(outDir);
  const result: GenerateResult = {
    outputRoot: outRel,
    written: [],
    unchanged: [],
    conflicts: [],
    removed: [],
    keptStale: [],
    cases: caseMap,
    skipped: plan.cases
      .filter((c) => c.status !== 'READY')
      .map((c) => ({ id: c.id, status: c.status })),
    formatted,
  };
  const manifest: Manifest = { schemaVersion: 1, generator: 'qa-agent', planHash: hash, files: {} };

  for (const [file, content] of files) {
    const target = path.join(outDir, file);
    const rel = toPosix(path.join(outRel, file));
    if (fs.existsSync(target)) {
      const current = fs.readFileSync(target, 'utf8');
      const known = previous?.files[file];
      const ours = file === 'case-map.json' || current.includes(GENERATED_MARK);
      if (current === content) {
        result.unchanged.push(rel);
        manifest.files[file] = sha(content);
        continue;
      }
      if (
        !ours ||
        (known !== undefined && sha(current) !== known) ||
        (known === undefined && previous !== null)
      ) {
        // A custom file, or a generated file the user edited: never overwrite it.
        const proposed = `${file}.qa-agent-new`;
        writeProjectFile(projectRoot, config, path.join(outRel, proposed), content);
        result.conflicts.push({
          file: rel,
          reason: ours ? 'edited since it was generated' : 'not a QA Agent file',
          proposed: toPosix(path.join(outRel, proposed)),
        });
        if (known !== undefined) manifest.files[file] = known;
        continue;
      }
    }
    writeProjectFile(projectRoot, config, path.join(outRel, file), content);
    manifest.files[file] = sha(content);
    result.written.push(rel);
  }

  for (const [file, known] of Object.entries(previous?.files ?? {})) {
    if (files.has(file)) continue;
    const target = path.join(outDir, file);
    if (!fs.existsSync(target)) continue;
    if (sha(fs.readFileSync(target, 'utf8')) === known) {
      fs.rmSync(assertWritable(projectRoot, config, path.join(outRel, file)));
      result.removed.push(toPosix(path.join(outRel, file)));
    } else {
      result.keptStale.push(toPosix(path.join(outRel, file)));
    }
  }
  writeProjectFile(
    projectRoot,
    config,
    path.join(outRel, MANIFEST),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );
  return result;
}

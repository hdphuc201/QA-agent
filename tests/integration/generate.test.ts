// P4 acceptance: plan → generated Playwright specs (compile, discovery, golden, idempotency, guards).
// Golden files: tests/golden/sample-app/. Regenerate them with UPDATE_GOLDEN=1 after a reviewed change.

import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { after, describe, test } from 'node:test';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import { parseProjectConfig, type ProjectConfig } from '../../src/config/project-config.schema.ts';
import { WriteDeniedError } from '../../src/config/write-guard.ts';
import { FORMAT_OPTIONS, runGenerate } from '../../src/generator/generate.ts';
import { validateGenerated } from '../../src/generator/validate.ts';
import { TestPlanSchema, type TestPlan } from '../../src/planning/schema.ts';
import { copySampleApp } from '../helpers/sample-app.ts';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const golden = path.join(repoRoot, 'tests/golden/sample-app');
const runtimeFile = path.join(repoRoot, 'src/generator/runtime/qa-agent.fixtures.ts');
const fixturePlan = TestPlanSchema.parse(
  JSON.parse(fs.readFileSync(path.join(repoRoot, 'tests/fixtures/sample-test-plan.json'), 'utf8')),
);
const temps: string[] = [];
after(() => temps.forEach((t) => fs.rmSync(t, { recursive: true, force: true })));

function project(): { root: string; config: ProjectConfig } {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'qa generate '));
  temps.push(root);
  copySampleApp(root);
  // The target project's own @playwright/test (a junction needs no admin rights on Windows).
  fs.symlinkSync(path.join(repoRoot, 'node_modules'), path.join(root, 'node_modules'), 'junction');
  fs.writeFileSync(path.join(root, 'package.json'), '{"name":"sample-target","private":true}\n');
  return {
    root,
    config: parseProjectConfig(
      JSON.parse(fs.readFileSync(path.join(root, '.qa-agent/config.json'), 'utf8')),
      'cfg',
    ),
  };
}

const gen = (root: string, config: ProjectConfig, plan: TestPlan = fixturePlan) =>
  runGenerate({ projectRoot: root, config, plan, runtimeFile });
const out = (root: string, f = '') => path.join(root, 'e2e/generated', f);

describe('P4 gate: code generation', () => {
  test('generated specs compile, are discovered by Playwright and match the golden files', async () => {
    const { root, config } = project();
    const res = await gen(root, config);
    assert.equal(res.cases.length, 19);
    assert.deepEqual(res.skipped, [
      { id: 'DEMO-REQ-VIEW-001-001', status: 'NEEDS_REVIEW' },
      { id: 'DEMO-REQ-REQ-004-001', status: 'NEEDS_REVIEW' },
    ]);
    assert.equal(res.formatted, true);

    const v = validateGenerated({
      projectRoot: root,
      outputRoot: config.testOutputRoot,
      pluginRoot: repoRoot,
      expected: 19,
    });
    assert.equal(v.typecheck.ok, true, v.typecheck.output);
    assert.equal(v.listed, 19, v.listOutput);
    assert.deepEqual(v.problems, []);

    const files = fs
      .readdirSync(out(root))
      .filter((f) => f !== '.qa-agent-manifest.json')
      .sort();
    if (process.env.UPDATE_GOLDEN === '1') {
      fs.rmSync(golden, { recursive: true, force: true });
      fs.mkdirSync(golden, { recursive: true });
      for (const f of files) fs.copyFileSync(out(root, f), path.join(golden, f));
    }
    assert.deepEqual(files, fs.readdirSync(golden).sort(), 'same generated file set');
    for (const f of files) {
      assert.equal(
        fs.readFileSync(out(root, f), 'utf8'),
        fs.readFileSync(path.join(golden, f), 'utf8'),
        `golden mismatch: ${f}`,
      );
      if (f.endsWith('.ts'))
        assert.ok(
          await prettier.check(fs.readFileSync(out(root, f), 'utf8'), FORMAT_OPTIONS),
          `${f} is formatted`,
        );
    }
    for (const f of files.filter((x) => x.endsWith('.spec.ts'))) {
      const src = fs.readFileSync(out(root, f), 'utf8');
      assert.match(src, /^\/\/ GENERATED by QA Agent/);
      assert.doesNotMatch(
        src,
        /alice-demo|bob-demo|victor-demo/,
        'no credentials in generated code',
      );
    }
  });

  test('regeneration is stable; edited and custom files are never overwritten; stale files are removed', async () => {
    const { root, config } = project();
    const first = await gen(root, config);
    const second = await gen(root, config);
    assert.deepEqual(second.written, []);
    assert.equal(second.unchanged.length, first.written.length);

    // A user edits a generated spec and adds a custom spec.
    const edited = out(root, 'approval.spec.ts');
    fs.writeFileSync(edited, `${fs.readFileSync(edited, 'utf8')}\n// my tweak\n`);
    fs.writeFileSync(
      out(root, 'custom.spec.ts'),
      "import { test } from '@playwright/test';\ntest('mine', () => {});\n",
    );
    const third = await gen(root, config);
    assert.deepEqual(third.conflicts, [
      {
        file: 'e2e/generated/approval.spec.ts',
        reason: 'edited since it was generated',
        proposed: 'e2e/generated/approval.spec.ts.qa-agent-new',
      },
    ]);
    assert.match(fs.readFileSync(edited, 'utf8'), /\/\/ my tweak/);
    assert.ok(fs.existsSync(`${edited}.qa-agent-new`));
    assert.equal(
      fs.readFileSync(out(root, 'custom.spec.ts'), 'utf8').includes("test('mine'"),
      true,
    );
    const v = validateGenerated({
      projectRoot: root,
      outputRoot: config.testOutputRoot,
      pluginRoot: repoRoot,
      expected: 19,
    });
    assert.equal(v.listed, 19, 'custom tests are not counted as generated ones');

    // A plan without Authentication cases: its unmodified spec is removed; the edited one is kept.
    const reduced = {
      ...fixturePlan,
      cases: fixturePlan.cases.filter(
        (c) => c.feature !== 'Authentication' && c.feature !== 'Approval',
      ),
    };
    const fourth = await gen(root, config, reduced);
    assert.deepEqual(fourth.removed, ['e2e/generated/authentication.spec.ts']);
    assert.deepEqual(fourth.keptStale, ['e2e/generated/approval.spec.ts']);
    assert.ok(fs.existsSync(out(root, 'custom.spec.ts')));
  });

  test('writes outside the allowlist or into read-only paths are refused', async () => {
    const { root, config } = project();
    await assert.rejects(
      gen(root, { ...config, testOutputRoot: 'docs/generated' }),
      WriteDeniedError,
    );
    assert.ok(!fs.existsSync(path.join(root, 'docs/generated')));
    // The schema already refuses an output root overlapping source or read-only paths.
    for (const bad of ['.', 'docs', 'docs/generated', 'server.mjs']) {
      assert.throws(
        () =>
          parseProjectConfig(
            {
              ...JSON.parse(fs.readFileSync(path.join(root, '.qa-agent/config.json'), 'utf8')),
              testOutputRoot: bad,
            },
            'cfg',
          ),
        /must not overlap/,
        bad,
      );
    }
  });

  test('validation reports BLOCKED when the target project has no @playwright/test', async () => {
    const { root, config } = project();
    await gen(root, config);
    fs.rmSync(path.join(root, 'node_modules'));
    const v = validateGenerated({
      projectRoot: root,
      outputRoot: config.testOutputRoot,
      pluginRoot: repoRoot,
      expected: 19,
    });
    assert.equal(v.ok, false);
    assert.ok(v.problems.includes('BLOCKED: the target project has no @playwright/test installed'));
  });
});

#!/usr/bin/env node
// Builds bin/qa-agent.mjs: the engine CLI as one self-contained ES module (zod included), so an
// installed plugin (a git checkout without node_modules) runs with plain `node`. The bundle is
// committed; `--check` fails when it is out of date with src/ (used in CI).
//
//   node scripts/bundle.mjs [--check]

import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outfile = path.join(root, 'bin/qa-agent.mjs');
const check = process.argv.includes('--check');

const result = await build({
  entryPoints: [path.join(root, 'src/cli.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  write: false,
  outfile,
  legalComments: 'eof',
  // Optional formatter, loaded at run time from the plugin checkout or the target project.
  external: ['prettier'],
  logLevel: 'warning',
  banner: {
    js: '// GENERATED by scripts/bundle.mjs from src/ — do not edit. Includes zod (MIT, https://github.com/colinhacks/zod).',
  },
});
const code = result.outputFiles[0]?.text ?? '';

if (check) {
  const current = fs.existsSync(outfile) ? fs.readFileSync(outfile, 'utf8') : '';
  if (current !== code) {
    console.error('bin/qa-agent.mjs is out of date: run `npm run bundle` and commit it');
    process.exit(1);
  }
  console.log('bin/qa-agent.mjs is up to date');
} else {
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  fs.writeFileSync(outfile, code);
  console.log(`wrote bin/qa-agent.mjs (${Math.round(code.length / 1024)} KiB)`);
}
